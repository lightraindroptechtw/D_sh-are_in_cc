const STRINGS = { 'zh-Hant': zhHant, 'zh-Hans': zhHans, en, ja, ko, es, fr, ru, ar };
const STORE = 'dsh-lang';

/** 第一次打開：系統／瀏覽器語言是 9 種之一就用它（中文依地區分繁簡），不是的話用英文。 */
function guess() {
  for (const tag of navigator.languages ?? [navigator.language]) {
    const lower = String(tag).toLowerCase();
    if (lower.startsWith('zh')) return /hans|cn|sg|my/.test(lower) ? 'zh-Hans' : 'zh-Hant';
    const base = lower.split('-')[0];
    if (STRINGS[base]) return base;
  }
  return 'en';
}

let current = (() => {
  try { const saved = localStorage.getItem(STORE); if (saved && STRINGS[saved]) return saved; } catch { /* 記不住就用猜的 */ }
  return guess();
})();

export const lang = () => current;
export const langInfo = () => LANGS.find(item => item.code === current) ?? LANGS[0];

export function setLang(code) {
  if (!STRINGS[code]) return;
  current = code;
  try { localStorage.setItem(STORE, code); } catch { /* 記不住就算了 */ }
}

/** 取一句介面文字，把 {名稱} 換成 vars 裡的值；回傳字串。 */
export function t(key, vars = {}) {
  const text = STRINGS[current][key] ?? zhHant[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (all, name) => (name in vars ? String(vars[name]) : all));
}

/** 同 t，但 vars 的值可以是畫面元素（例如加粗的數字）；回傳一串文字和元素，交給 h() 放進畫面。 */
export function tParts(key, vars = {}) {
  const text = STRINGS[current][key] ?? zhHant[key] ?? key;
  return text.split(/(\{\w+\})/).filter(Boolean).map(part => {
    const name = /^\{(\w+)\}$/.exec(part)?.[1];
    return name && name in vars ? vars[name] : part;
  });
}

/** 有沒有這句介面文字（伺服器送來的訊息代碼要先確認網頁認得）。 */
export const hasKey = key => key in zhHant;

/** 測試用：每種語言缺哪些句子、多了哪些句子。 */
export function missingKeys() {
  const keys = Object.keys(zhHant);
  return Object.fromEntries(Object.entries(STRINGS).map(([code, table]) => [code, { missing: keys.filter(key => !(key in table)), extra: Object.keys(table).filter(key => !(key in zhHant)) }]));
}
